class Case:
    def __init__(self, name, balance, matrix, imps, targets, endpoints, base, waste, doc=None, waste_only=False):
        self.name, self.balance, self.matrix, self.imps = name, balance, dict(matrix), dict(imps)
        self.targets, self.endpoints, self.base, self.waste = list(targets), endpoints, base, waste
        self.doc, self.waste_only = doc, waste_only
        self.props = None
        self.example = doc is not None

    @property
    def elements(self):
        return [self.balance] + list(self.matrix) + list(self.imps)

    def nominal(self):
        return {i: v[0] for i, v in self.imps.items()}


def norm_imps(raw):
    out = {}
    for i, v in raw.items():
        if isinstance(v, dict):
            out[el_key(i)] = (v["nominal"], v["min"], v["max"])
        else:
            out[el_key(i)] = (v, v, v)
    return out


def build_cases(data_home, photon, props_for):
    """The declared cases (and the worked example in place of ra_steel when present)."""
    cases = []
    example = EXAMPLE_DIR / "impurities.json"
    for name, d in CASE_DEFS.items():
        waste = {"mass_g": WASTE_MASS_G, "displaced_volume_cm3": WASTE_MASS_G / d["density"],
                 "waste_type": WASTE_TYPE}
        base = make_base(data_home, photon if not d.get("waste_only") else None)
        eps = [{"response": "waste_class", "class": "C"}] if d.get("waste_only") else \
            [{"response": "activity.total"}, {"response": "heat.total"}, {"response": f"activity:{d['nuclide']}"},
             {"response": "clearance_index"}, {"response": "waste_class", "class": "C"}]
        if photon and not d.get("waste_only"):
            eps.insert(3, {"response": "dose.contact_proxy"})
        if name == "ra_steel" and example.is_file():
            cases.append(case_from_example(example, data_home, waste))
            continue
        c = Case(name, d["balance"], d["matrix"], norm_imps(d["impurities"]), TARGETS, eps, base, waste,
                 waste_only=bool(d.get("waste_only")))
        cases.append(c)
    for c in cases:
        c.props = props_for(c.base)
    return cases


def case_from_example(path, data_home, waste_default):
    """The worked example as a case: its own endpoints, targets and base spec; waste geometry from its fields."""
    doc = json.loads(Path(path).read_text())
    b = doc["base_spec"]
    base = b if isinstance(b, dict) else json.loads((Path(path).parent / b).read_text())
    base = copy.deepcopy(base)
    base.pop("uncertainty", None)
    waste = dict(waste_default)
    srcs = [doc] + [e for e in doc.get("endpoints", []) if e.get("response") == "waste_class"]
    for src in srcs:
        for k in ("mass_g", "waste_type"):
            if k in src:
                waste[k] = src[k]
        if "displaced_volume_cm3" in src:
            waste["displaced_volume_cm3"] = src["displaced_volume_cm3"]
        elif "density_g_cm3" in src:
            waste["displaced_volume_cm3"] = waste["mass_g"] / src["density_g_cm3"]
    return Case("ra_steel", el_key(doc["balance"]), {el_key(k): v for k, v in doc["matrix"].items()},
                norm_imps(doc["impurities"]), doc["targets"], doc["endpoints"], base, waste, doc=doc)


class State:
    """Pure-element runs, the linear model and the command's output for one case."""

    def __init__(self, case, solver, clr, work, binary, cwd, timeout):
        self.case, self.solver, self.clr, self.work = case, solver, clr, Path(work) / case.name
        self.binary, self.cwd, self.timeout = binary, cwd, timeout
        self.pure = {}
        self.cmd = None
        self.rc = None
        self.cmd_info = {}

    def pure_runs(self):
        if self.pure:
            return self.pure
        for el in self.case.elements:
            self.pure[el], _ = self.solver.solve(pure_spec(self.case, el))
        return self.pure

    def r(self, ep, step):
        return {el: endpoint_value(self.pure_runs()[el], step, ep, self.clr) for el in self.case.elements}

    def choose_limits(self):
        """Give heat.total and the nuclide endpoint a limit: geometric mean of the smallest and largest nominal value
        over the targets (from the pure runs). The worked example keeps its own."""
        if self.case.example:
            return
        for ep in self.case.endpoints:
            if ep["response"] == "heat.total" or ep["response"].startswith("activity:"):
                vals = []
                for st in self.case.targets:
                    a = analyse(self.r(ep, st), self.case.balance, self.case.matrix, self.case.imps)
                    if a["nominal"] > 0.0:
                        vals.append(a["nominal"])
                ep["limit"] = math.sqrt(min(vals) * max(vals)) if vals else 1.0

    def run_command(self, tag="main"):
        """`actinv impurities IN OUT` on this case's input. Cached per State."""
        if self.cmd is not None:
            return self.cmd
        case = self.case
        self.pure_runs()
        self.choose_limits()
        d = self.work / tag
        d.mkdir(parents=True, exist_ok=True)
        dump(d / "base_spec.json", case.base)
        doc = impurities_doc(case)
        dump(d / "impurities.json", doc)
        out = d / "out.json"
        if out.exists():
            out.unlink()
        code, so, se = run_cmd([self.binary, "impurities", d / "impurities.json", out], self.timeout, self.cwd,
                               clean_env())
        self.rc = code
        self.cmd_info = {"exit": code, "stderr_tail": se.decode(errors="replace")[-600:], "input": str(d / "impurities.json"),
                         "input_sha256": sha256_file(d / "impurities.json")}
        if code not in (0, 3) or not out.is_file():
            raise GateError(f"actinv impurities failed ({code}): {se.decode(errors='replace')[-600:]}")
        self.cmd = json.loads(out.read_text())
        self.cmd_info["output_sha256"] = sha256_file(out)
        return self.cmd


