    def guarded(name, fn):
        try:
            g[name] = fn()
        except (GateError, SchemaError, KeyError, ValueError, IndexError, TypeError, OSError, AttributeError,
                MissingInput) as error:
            g[name] = {"pass": False, "error": f"{type(error).__name__}: {error}"}
        print(f"P157 {name}: {'PASS' if g[name].get('pass') else 'FAIL'}"
              + (f" ERROR {g[name]['error']}" if "error" in g[name] else ""))
