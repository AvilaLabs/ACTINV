def activities_at(case, pure_acts, levels):
    """Linear combination of the pure runs' nuclide activities (Bq/g) at a composition: {nuclide: Bq/g}."""
    comp = composition(case, levels)
    out = {}
    for el, w in comp.items():
        for n, a in pure_acts[el].items():
            out[n] = out.get(n, 0.0) + w * a / 100.0
    return out


def worst_class_from_sums(case, pack, pure_acts_step, props):
    """Class of the separately maximised table sums at one target. pure_acts_step {el: {nuclide: Bq/g}}."""
    w = case.waste
    mass, vol = w["mass_g"], w["displaced_volume_cm3"]
    fr_pure = {el: fractions(pack, w["waste_type"], mass, vol, {n: a * mass for n, a in acts.items()}, props)[0]
               for el, acts in pure_acts_step.items()}
    s_pure = {el: {k: math.fsum(v.values()) for k, v in fr.items()} for el, fr in fr_pure.items()}
    worst = {}
    for key in SUM_KEYS:
        r = {el: s_pure[el][key] for el in s_pure}
        a = analyse(r, case.balance, case.matrix, case.imps)
        lv = a["worst_level"]
        acts = activities_at(case, pure_acts_step, lv)
        fr, _ = fractions(pack, w["waste_type"], mass, vol, {n: x * mass for n, x in acts.items()}, props)
        worst[key] = (a["worst"], sum(1 for x in fr[key].values() if x > 0.0), fr[key])
    sums = {k: (v[0], v[1]) for k, v in worst.items()}
    cls, cons = class_from_sums(sums)
    return cls, cons, {k: v[0] for k, v in worst.items()}


def qualifies_composition_solve(case):
    elems = set(case.elements)
    if len(elems) > 8:
        return f"{len(elems)} elements (limit 8)"
    bad = sorted(e for e in elems if e not in QUALIFIED)
    if bad:
        return f"elements not among the 26 qualified: {bad}"
    if len(case.targets) > 4:
        return "more than 4 targets"
    if case.base.get("photon"):
        return "non-default photon section in the base spec"
    return None


