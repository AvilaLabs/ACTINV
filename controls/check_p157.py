CLASS_ORDER = ["A", "B", "C", "GTCC"]


def norm_class(text):
    t = str(text).strip().upper().replace(" ", "_")
    if t in ("A", "B", "C"):
        return t
    if t in ("GTCC", "ABOVE_CLASS_C", "ABOVE_C", ">C", "GREATER_THAN_C") or "ABOVE" in t or "GTCC" in t:
        return "GTCC"
    if t in ("UNKNOWN",):
        return "unknown"
    raise ValueError(f"unrecognised class {text!r}")


def class_rank(c):
    return CLASS_ORDER.index(c)


def norm_status(text):
    """'limit' | 'no_response' | 'infeasible' from a free status string; None when none matches."""
    t = str(text).lower()
    if "infeasible" in t:
        return "infeasible"
    if "no " in t and "response" in t or "no_response" in t:
        return "no_response"
    if t.startswith("limit") or t in ("ok", "feasible"):
        return "limit"
    return None


# ------------------------------------------------------------------------------ OUT path lookup


def rd(doc, key, optional=False, **fmt):
    """Value at OUT[key] with the placeholders filled. SchemaError('schema key not found: ...') when missing; with
    optional=True returns the sentinel MISSING instead."""
    path = OUT[key].format(**fmt) if key in OUT else key.format(**fmt)
    return walk(doc, path, optional)


MISSING = object()


def walk(doc, path, optional=False):
    node = doc
    for seg in path.split("/"):
        m = re.fullmatch(r"\[([^=\]]+)=(.*)\]", seg)
        ok = False
        if m:
            field, want = m.group(1), m.group(2)
            if isinstance(node, dict) and want in node:
                node, ok = node[want], True
            elif isinstance(node, list):
                for el in node:
                    if isinstance(el, dict) and str(el.get(field)) == want:
                        node, ok = el, True
                        break
        elif isinstance(node, dict) and seg in node:
            node, ok = node[seg], True
        elif isinstance(node, list) and re.fullmatch(r"\d+", seg) and int(seg) < len(node):
            node, ok = node[int(seg)], True
        if not ok:
            if optional:
                return MISSING
            raise SchemaError(f"schema key not found: {path} (no {seg!r})")
    return node


# ------------------------------------------------------------------------------ Part 61 classifier (own)


class Pack:
    def __init__(self, path=PACK_FILE):
        doc = json.loads(Path(path).read_text())
        self.id, self.ci_bq, self.year_s, self.rows = doc["id"], doc["ci_bq"], doc["year_s"], doc["rows"]
        self.sha256 = sha256_file(path)

    def rows_for(self, table, waste_type):
        return [r for r in self.rows if r["table"] == table and r["applicability"] in ("all", waste_type)]


ALPHA_ROW, SHORT_ROW = "alpha_transuranic_gt5y", "half_life_lt5y"
SUM_KEYS = ("T1", "T2c1", "T2c2", "T2c3")


def fractions(pack, waste_type, mass_g, volume_cm3, activity_bq, props):
    """{sum key: {nuclide: fraction of that key's limit}} for whole-component activities (Bq) by canonical nuclide;
    props {nuclide: (z, half_life_s, alpha_emitting)}. Returns (fractions, unknown nuclides)."""
    out = {k: {} for k in SUM_KEYS}
    unknown = []
    t1, t2 = pack.rows_for(1, waste_type), pack.rows_for(2, waste_type)

    def frac(bq, row, limit):
        if row["unit"] == "Ci/m3":
            return bq / (limit * pack.ci_bq * volume_cm3 * 1.0e-6)
        return bq / (limit * pack.ci_bq * 1.0e-9 * mass_g)

    for n in sorted(activity_bq):
        bq = activity_bq[n]
        if not bq > 0.0:
            continue
        if n not in props:
            unknown.append(n)
            continue
        z, half_life_s, alpha = props[n]
        years = half_life_s / pack.year_s
        named = [r for r in t1 if r["selector"] != ALPHA_ROW and nuc_key(r["selector"]) == n]
        if named:
            out["T1"][n] = frac(bq, named[0], named[0]["limits"][0])
        else:
            a = [r for r in t1 if r["selector"] == ALPHA_ROW]
            if a and z > 92 and alpha and years > 5.0:
                out["T1"][n] = frac(bq, a[0], a[0]["limits"][0])
        named2 = [r for r in t2 if r["selector"] != SHORT_ROW and nuc_key(r["selector"]) == n]
        short = [r for r in t2 if r["selector"] == SHORT_ROW]
        row2 = named2[0] if named2 else (short[0] if short and years < 5.0 else None)
        if row2 is not None:
            for c in range(3):
                if row2["limits"][c] is not None:
                    out[f"T2c{c + 1}"][n] = frac(bq, row2, row2["limits"][c])
    return out, unknown


def sums_of(fr):
    """{key: (sum, contributor count)} from fractions()."""
    return {k: (math.fsum(v.values()), sum(1 for x in v.values() if x > 0.0)) for k, v in fr.items()}


def passes(x, count):
    return x < 1.0 if count > 1 else x <= 1.0


def class_from_sums(sums):
    """Class letter ('A','B','C','GTCC') and the constraint list from {key: (sum, count)}."""
    s1, n1 = sums["T1"]
    cons = []
    result = "GTCC"
    for cls, col, thr in (("A", "T2c1", 0.1), ("B", "T2c2", 0.1), ("C", "T2c3", 1.0)):
        s2, n2 = sums[col]
        ok1, ok2 = passes(s1 / thr, n1), passes(s2, n2)
        cons.append({"class": cls, "T1": s1 / thr, "col": col, "T2": s2, "ok": ok1 and ok2})
        if ok1 and ok2 and result == "GTCC":
            result = cls
    return result, cons


def classify(pack, waste_type, mass_g, volume_cm3, activity_bq, props):
    fr, unknown = fractions(pack, waste_type, mass_g, volume_cm3, activity_bq, props)
    cls, cons = class_from_sums(sums_of(fr))
    return ("unknown" if unknown else cls), cons, unknown


def binding_of(cons, result):
    """(table, column) of the largest failed sum at the class below `result` (None for class A)."""
    if result in ("A", "unknown"):
        return None
    below = CLASS_ORDER[class_rank(result) - 1]
    row = next(c for c in cons if c["class"] == below)
    return ("1", None) if row["T1"] >= row["T2"] else ("2", int(row["col"][-1]))


# ------------------------------------------------------------------------------ linear model (pure arithmetic)


def f_lin(r, bal, w):
    """Endpoint of composition w {element: wt%} (the balance is the remainder) from pure values r."""
    rest = 100.0 - sum(v for k, v in w.items() if k != bal)
    return (rest * r[bal] + sum(v * r[k] for k, v in w.items() if k != bal)) / 100.0


def lin_status(g, scale):
    return "no_response" if g <= ABS_FLOOR * scale else None


def limit_from(g, base, L, scale):
    """(status, wt%) of the impurity weight reaching limit L from `base` (endpoint with the impurity at 0)."""
    s = lin_status(g, scale)
    if s:
        return s, None
    num = L - base
    if num < 0.0:
        return "infeasible", None
    return "limit", num / g


def analyse(r, bal, matrix, imps, L=None):
    """Closed-form linear analysis. imps {el: (nominal, min, max)}. Returns a dict (see keys)."""
    scale = max(abs(v) for v in r.values()) or 1.0
    g = {i: (r[i] - r[bal]) / 100.0 for i in imps}
    base = dict(matrix)
    f_matrix = f_lin(r, bal, base)
    nom = {i: imps[i][0] for i in imps}
    f_nom = f_lin(r, bal, {**base, **nom})
    worst_level = {i: (imps[i][2] if g[i] > 0.0 else imps[i][1]) for i in imps}
    worst_corner = {i: ("max" if g[i] > 0.0 else "min") for i in imps}
    f_worst = f_lin(r, bal, {**base, **worst_level})
    out = {"scale": scale, "gradient": g, "matrix_only": f_matrix, "nominal": f_nom, "worst": f_worst,
           "worst_corner": worst_corner, "worst_level": worst_level,
           "contribution": {i: nom[i] * g[i] for i in imps},
           "contribution_max": {i: imps[i][2] * g[i] for i in imps}}
    if L is not None:
        lim = {"alone": {}, "others_nominal": {}, "others_worst": {}}
        for i in imps:
            lim["alone"][i] = limit_from(g[i], f_matrix, L, scale)
            lim["others_nominal"][i] = limit_from(g[i], f_nom - nom[i] * g[i], L, scale)
            others = f_matrix + sum(worst_level[j] * g[j] for j in imps if j != i)
            lim["others_worst"][i] = limit_from(g[i], others, L, scale)
        out["limits"] = lim
        d = f_nom - f_matrix
        if d <= ABS_FLOOR * scale:
            out["joint"] = ("no_response", None)
        elif L < f_matrix:
            out["joint"] = ("infeasible", None)
        else:
            out["joint"] = ("limit", (L - f_matrix) / d)
    return out


def rank_by(contrib):
    """Impurity names ordered by contribution (RANK_BY), ties by name."""
    key = (lambda i: (-contrib[i], i)) if RANK_BY == "signed" else (lambda i: (-abs(contrib[i]), i))
    return sorted(contrib, key=key)


def top_nuclides(nv_i, nv_b, w_i, contribution, n=3):
    """[(nuclide, c)] the n largest c = w_i (v_i - v_b)/100 of the sign of `contribution` (largest when >= 0)."""
    sign = 1.0 if contribution >= 0.0 else -1.0
    cs = {}
    for k in set(nv_i) | set(nv_b):
        c = w_i * (nv_i.get(k, 0.0) - nv_b.get(k, 0.0)) / 100.0
        if c * sign > 0.0:
            cs[k] = c
    return sorted(cs.items(), key=lambda kv: (-kv[1] * sign, kv[0]))[:n]


def corners(names, imps):
    """All 2^n corners of the impurity box: list of ({el: "min"|"max"}, {el: level})."""
    out = []
    for combo in itertools.product(("min", "max"), repeat=len(names)):
        lab = dict(zip(names, combo))
        out.append((lab, {i: imps[i][1 if lab[i] == "min" else 2] for i in names}))
    return out


def check_order(theirs, values, mine_sorted, rel, scale):
    """theirs is a valid ordering: the same names as `values`, value sequence equal to mine_sorted within rel."""
    names = [name_of(x) for x in theirs]
    if sorted(map(str, names)) != sorted(map(str, values)):
        return False, f"names {names} vs {sorted(values)}"
    for k, nm in enumerate(names):
        if not close(values[str(nm) if str(nm) in values else nm], mine_sorted[k], rel, scale):
            return False, f"position {k}: {nm} has {values[nm]!r}, expected {mine_sorted[k]!r}"
    return True, ""


