class Checks:
    def __init__(self):
        self.n = 0
        self.nfail = 0
        self.failures = []
        self.max_rel = 0.0
        self.notes = []

    def ok(self, cond, name, expected=None, observed=None):
        self.n += 1
        if not cond:
            self.nfail += 1
            if len(self.failures) < MAX_LISTED:
                self.failures.append({"check": name, "expected": expected, "observed": observed})
        return bool(cond)

    def num(self, name, expected, observed, rel, scale=0.0):
        good = isinstance(observed, (int, float)) and not isinstance(observed, bool) \
            and close(expected, observed, rel, scale)
        if isinstance(observed, (int, float)) and isinstance(expected, (int, float)) and math.isfinite(expected) \
                and abs(expected - observed) > ABS_FLOOR * abs(scale):
            self.max_rel = max(self.max_rel, reldiff(expected, observed))
        return self.ok(good, name, expected, observed)

    def guard(self, name, fn):
        """Run fn(); a SchemaError becomes a failed check carrying the message."""
        try:
            return fn()
        except SchemaError as error:
            self.ok(False, name, "present", str(error))
        return None

    def summary(self, **extra):
        return {"pass": self.nfail == 0, "checks": self.n, "failures": self.nfail, "max_rel_dev": self.max_rel,
                "failure_list": self.failures, "notes": self.notes, **extra}


def parse_corner(node, imps):
    """{imp: 'min'|'max'|None-for-other} from a reported corner (strings or wt% values)."""
    out = {}
    for i, (nom, lo, hi) in imps.items():
        if i not in node:
            raise SchemaError(f"schema key not found: corner entry for {i}")
        v = node[i]
        if isinstance(v, str):
            t = v.lower()
            out[i] = "min" if t in ("min", "lower", "low") else "max" if t in ("max", "upper", "high") else None
        else:
            out[i] = "min" if close(v, lo, 1e-9) else "max" if close(v, hi, 1e-9) else None
    return out


def corner_levels(corner, imps):
    return {i: (imps[i][1] if m == "min" else imps[i][2]) for i, m in corner.items() if m}


