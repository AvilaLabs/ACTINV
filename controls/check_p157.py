def fenced_blocks(text):
    """[(info, body, preceding label line)] of the fenced code blocks of a markdown text."""
    out, lines, i = [], text.splitlines(), 0
    last = ""
    while i < len(lines):
        m = re.match(r"^```(\S*)\s*$", lines[i])
        if m:
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append((m.group(1), "\n".join(lines[i + 1:j]), last))
            i = j + 1
            last = ""
            continue
        if lines[i].strip():
            last = lines[i].strip()
        i += 1
    return out


def line_run_in(block, output):
    """True when the non-empty lines of block (right-stripped) occur as a contiguous run in the output's lines."""
    b = [ln.rstrip() for ln in block.splitlines() if ln.strip()]
    o = [ln.rstrip() for ln in output.splitlines() if ln.strip()]
    return bool(b) and any(o[k:k + len(b)] == b for k in range(len(o) - len(b) + 1))


def chapter_pairs(text):
    """[(command line, output block)] where a fenced block labelled Output follows an `actinv impurities` block."""
    pairs, blocks = [], fenced_blocks(text)
    for k, (info, body, label) in enumerate(blocks):
        if k and "output" in (label.lower() + " " + info.lower()):
            cmds = [ln.strip().lstrip("$ ").strip() for ln in blocks[k - 1][1].splitlines()
                    if "actinv impurities" in ln]
            if cmds:
                pairs.append((cmds[-1], body))
    return pairs


