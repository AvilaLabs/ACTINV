def find_data_home(cwd):
    cands = [Path(cwd)]
    code, so, _ = run_cmd(["git", "rev-parse", "--git-common-dir"], 30, ROOT)
    if code == 0:
        cands.append((ROOT / so.decode().strip()).resolve().parent)
    for c in cands:
        if (c / "actinv-data" / "v1.1.0").is_dir():
            return c
    raise MissingInput("actinv-data/v1.1.0 not found in the working directory or the main checkout; pass --cwd")


