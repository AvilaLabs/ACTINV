def composition(case, levels, balance_only=None):
    """{element: wt%} of the full material: matrix, impurities at `levels` (missing = 0), balance remainder."""
    comp = dict(case.matrix)
    for i, v in levels.items():
        if v > 0.0:
            comp[i] = comp.get(i, 0.0) + v
    comp[case.balance] = 100.0 - sum(comp.values())
    if comp[case.balance] < 0.0:
        return None
    return {k: v for k, v in comp.items() if v > 0.0}


