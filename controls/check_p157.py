DROP_KEYS = ("ms", "elapsed_ms", "wall_time_s", "cells_per_s")


def normalize_result(obj):
    if isinstance(obj, dict):
        return {k: normalize_result(v) for k, v in obj.items() if k not in DROP_KEYS}
    if isinstance(obj, list):
        return [normalize_result(v) for v in obj]
    return obj


def json_diffs(a, b, path="", out=None, limit=20):
    out = [] if out is None else out
    if len(out) >= limit:
        return out
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if k not in a or k not in b:
                out.append({"path": f"{path}/{k}", "ref": a.get(k, "<absent>"), "cand": b.get(k, "<absent>")})
            else:
                json_diffs(a[k], b[k], f"{path}/{k}", out, limit)
    elif isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        for k, (x, y) in enumerate(zip(a, b)):
            json_diffs(x, y, f"{path}/{k}", out, limit)
    elif a != b:
        out.append({"path": path, "ref": a if len(str(a)) < 200 else str(a)[:200], "cand": b if len(str(b)) < 200 else str(b)[:200]})
    return out


