def gate_g2(ref, cand, work, data_home, timeout, props_of):
    items = g2_inputs(work, data_home, props_of)
    results, ok = [], True
    for ident, words, path, cwd in items:
        row = {"id": ident, "command": " ".join(words), "input": str(path)}
        outs = {}
        for label, binary in (("reference", ref), ("candidate", cand)):
            out = work / "g2" / f"{ident}.{label}.json"
            out.parent.mkdir(parents=True, exist_ok=True)
            if out.exists():
                out.unlink()
            code, so, se = run_cmd([binary, *words, path, out], timeout, cwd, clean_env())
            doc = None
            if out.is_file():
                try:
                    doc = json.loads(out.read_text())
                except ValueError:
                    doc = None
            outs[label] = (code, doc, se.decode(errors="replace")[-200:], sha256_file(out) if out.is_file() else None)
        (rc, rd_, re_, _), (cc, cd, ce, _) = outs["reference"], outs["candidate"]
        diffs = json_diffs(normalize_result(rd_), normalize_result(cd)) if rd_ is not None and cd is not None else []
        same = rc == cc and (rd_ is None) == (cd is None) and not diffs
        row.update({"reference_exit": rc, "candidate_exit": cc, "reference_output": rd_ is not None,
                    "diffs": diffs, "identical_apart_from_ms": same,
                    "reference_stderr": re_ if not same else "", "candidate_stderr": ce if not same else ""})
        row["pass"] = same and rc == 0
        ok = ok and row["pass"]
        results.append(row)
    return {"pass": ok, "cases": results}


