# ------------------------------------------------------------------------------ process execution


def run_cmd(argv, timeout, cwd, env=None):
    """Run without a shell in its own session. Returns (exit code or None, stdout, stderr)."""
    try:
        proc = subprocess.Popen([str(a) for a in argv], cwd=str(cwd), env=env, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, start_new_session=True)
    except OSError as error:
        return None, b"", f"{type(error).__name__}: {error}".encode()
    try:
        out, err = proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            proc.kill()
        proc.communicate()
        return None, b"", f"timed out after {timeout} s".encode()
    return proc.returncode, out, err


def clean_env():
    env = dict(os.environ)
    for name in ("ACTINV_LIBRARY", "ACTINV_ENDF_DECAY", "ACTINV_COVARIANCE"):
        env.pop(name, None)
    return env


def compact_of(result):
    """Per step {act: {nuclide: Bq/g}, heat, dose, nheat} from an `actinv run` result."""
    steps = []
    for s in result["steps"]:
        act = {nuc_key(k) or k: v for k, v in s["activity_Bq_per_g"].items() if v}
        h = s.get("heat_W_per_g")
        heat = h["total"] if isinstance(h, dict) else h
        ps = s.get("photon_source") or {}
        nheat = None
        rows = ((s.get("summary") or {}).get("nuclides"))
        if rows:
            nheat = {}
            for r in rows:
                v = (r.get("alpha_W") or 0.0) + (r.get("beta_W") or 0.0) + (r.get("gamma_W") or 0.0)
                if v:
                    nheat[nuc_key(r["nuclide"]) or r["nuclide"]] = v
        steps.append({"t_s": s.get("t_s"), "act": act, "heat": heat,
                      "dose": ps.get("contact_gamma_air_dose_proxy_Gy_h"), "nheat": nheat})
    return {"steps": steps}


class Solver:
    """`actinv run`, serial, memoised by the SHA-256 of the spec text under <work>/solves."""

    def __init__(self, binary, work, cwd, timeout):
        self.binary, self.dir, self.cwd, self.timeout = binary, Path(work) / "solves", cwd, timeout
        self.env = clean_env()
        self.count = 0
        self.hits = 0
        self.index = {}

    def solve(self, spec):
        """(compact, result path) of the spec's run."""
        keyed = {k: v for k, v in spec.items() if k != "title"}
        key = sha256_text(canonical(keyed))[:24]
        self.index[key] = spec.get("title")
        spec_p, out_p, cmp_p = (self.dir / f"{key}.{x}" for x in ("spec.json", "out.json", "compact.json"))
        if out_p.is_file() and cmp_p.is_file():
            self.hits += 1
            return json.loads(cmp_p.read_text()), out_p
        self.dir.mkdir(parents=True, exist_ok=True)
        spec_p.write_text(json.dumps(spec, indent=1) + "\n")
        if out_p.exists():
            out_p.unlink()
        code, so, se = run_cmd([self.binary, "run", spec_p, out_p], self.timeout, self.cwd, self.env)
        if code != 0 or not out_p.is_file():
            raise GateError(f"actinv run failed ({code}) for {spec.get('title')}: "
                            f"{(se or so).decode(errors='replace')[-400:]}")
        self.count += 1
        compact = compact_of(json.loads(out_p.read_text()))
        cmp_p.write_text(json.dumps(compact))
        return compact, out_p


# ------------------------------------------------------------------------------ endpoint values from a solve


class Clearance:
    def __init__(self, path=CLEARANCE_FILE):
        self.limits = {}
        for k, v in json.loads(Path(path).read_text())["limits"].items():
            self.limits[nuc_key(k)] = v

    def index(self, act):
        return math.fsum(a / self.limits[n] for n, a in act.items() if n in self.limits)

    def terms(self, act):
        return {n: a / self.limits[n] for n, a in act.items() if n in self.limits}


def endpoint_value(compact, step, ep, clr):
    """Scalar value of a scalar endpoint at one-based `step` from a compact solve."""
    s = compact["steps"][step - 1]
    r = ep["response"]
    if r == "activity.total":
        return math.fsum(s["act"].values())
    if r == "heat.total":
        return s["heat"]
    if r.startswith("activity:"):
        return s["act"].get(nuc_key(r.split(":", 1)[1]), 0.0)
    if r == "clearance_index":
        return clr.index(s["act"])
    if r == "dose.contact_proxy":
        if s["dose"] is None:
            raise GateError(f"contact dose proxy is null at step {step}")
        return s["dose"]
    raise ValueError(f"not a scalar endpoint: {r}")


def nuclide_values(compact, step, ep, clr):
    """Per-nuclide values behind a linear endpoint at `step` (None when the endpoint has none here)."""
    s = compact["steps"][step - 1]
    r = ep["response"]
    if r == "activity.total":
        return dict(s["act"])
    if r == "clearance_index":
        return clr.terms(s["act"])
    if r == "heat.total":
        return s["nheat"]
    return None


