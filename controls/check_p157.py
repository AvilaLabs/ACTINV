def compare_linear(st, cmd, ck):
    case = st.case
    imps = case.imps
    for ep in case.endpoints:
        if ep["response"] not in LINEAR and not ep["response"].startswith("activity:"):
            continue
        eid = endpoint_id(ep)
        L = ep.get("limit")
        per_step = {}
        for step in case.targets:
            r = st.r(ep, step)
            a = analyse(r, case.balance, case.matrix, imps, L)
            per_step[step] = a
            tag = f"{case.name}/{eid}/step{step}"
            sc = a["scale"]
            kw = {"endpoint": eid, "step": step}
            for key, mine in (("matrix_only", a["matrix_only"]), ("nominal", a["nominal"]), ("worst_value", a["worst"])):
                v = ck.guard(f"{tag}/{key}", lambda key=key: rd(cmd, key, **kw))
                if v is not None:
                    ck.num(f"{tag}/{key}", mine, v, REL_G3, sc)
            corner = ck.guard(f"{tag}/worst_corner", lambda: rd(cmd, "worst_corner", **kw))
            if corner is not None:
                try:
                    got = parse_corner(corner, imps)
                    for i in imps:
                        if abs(a["gradient"][i]) > 1e-9 * sc:
                            ck.ok(got[i] == a["worst_corner"][i], f"{tag}/worst_corner/{i}", a["worst_corner"][i], got[i])
                except SchemaError as error:
                    ck.ok(False, f"{tag}/worst_corner", "complete", str(error))
            for i in imps:
                for key, mine in (("gradient", a["gradient"][i]), ("contribution_nominal", a["contribution"][i]),
                                  ("contribution_max", a["contribution_max"][i])):
                    v = ck.guard(f"{tag}/{i}/{key}", lambda key=key: rd(cmd, key, imp=i, **kw))
                    if v is not None:
                        ck.num(f"{tag}/{i}/{key}", mine, v, REL_G3, sc)
            rank = ck.guard(f"{tag}/ranking", lambda: rd(cmd, "ranking", **kw))
            if rank is not None:
                good, why = check_order(rank, a["contribution"], [a["contribution"][i] for i in rank_by(a["contribution"])],
                                        REL_G3, sc)
                ck.ok(good, f"{tag}/ranking", rank_by(a["contribution"]), why or [name_of(x) for x in rank])
            nv_all = {el: nuclide_values(st.pure_runs()[el], step, ep, st.clr) for el in case.elements}
            if all(v is not None for v in nv_all.values()) and not ep["response"].startswith("activity:"):
                for i in imps:
                    mine = top_nuclides(nv_all[i], nv_all[case.balance], imps[i][0], a["contribution"][i])
                    got = ck.guard(f"{tag}/{i}/top_nuclides", lambda: rd(cmd, "top_nuclides", imp=i, **kw))
                    if got is not None:
                        names = [nuc_key(name_of(x)) or name_of(x) for x in got]
                        vals = {n: imps[i][0] * (nv_all[i].get(n, 0.0) - nv_all[case.balance].get(n, 0.0)) / 100.0
                                for n in set(nv_all[i]) | set(nv_all[case.balance])}
                        good = len(names) == len(mine) and all(n in vals for n in names) and \
                            all(close(vals[n], mine[k][1], REL_G3, sc) for k, n in enumerate(names))
                        ck.ok(good, f"{tag}/{i}/top_nuclides", [m[0] for m in mine], names)
            else:
                ck.notes.append(f"{tag}: top nuclides not checked (no per-nuclide values for {eid})")
            if L is not None:
                for kind, kname in KIND_NAMES.items():
                    for i in imps:
                        status, val = a["limits"][kind][i]
                        st_got = ck.guard(f"{tag}/{i}/{kind}/status", lambda: rd(cmd, "limit_status", imp=i, kind=kname, **kw))
                        if st_got is not None:
                            ck.ok(norm_status(st_got) == status, f"{tag}/{i}/{kind}/status", status, st_got)
                        if status == "limit":
                            v = ck.guard(f"{tag}/{i}/{kind}/value", lambda: rd(cmd, "limit_value", imp=i, kind=kname, **kw))
                            if v is not None:
                                ck.num(f"{tag}/{i}/{kind}/value", val, v, REL_G3)
                status, val = a["joint"]
                st_got = ck.guard(f"{tag}/joint/status", lambda: rd(cmd, "joint_k_status", **kw))
                if st_got is not None:
                    ck.ok(norm_status(st_got) == status, f"{tag}/joint/status", status, st_got)
                if status == "limit":
                    v = ck.guard(f"{tag}/joint/value", lambda: rd(cmd, "joint_k", **kw))
                    if v is not None:
                        ck.num(f"{tag}/joint/value", val, v, REL_G3)
        # summary across targets
        sc = max(a["scale"] for a in per_step.values())
        w = ck.guard(f"{case.name}/{eid}/summary/worst", lambda: rd(cmd, "summary_worst", endpoint=eid))
        if w is not None:
            ck.num(f"{case.name}/{eid}/summary/worst", max(a["worst"] for a in per_step.values()), w, REL_G3, sc)
        rk = ck.guard(f"{case.name}/{eid}/summary/ranking", lambda: rd(cmd, "summary_ranking", endpoint=eid))
        if rk is not None:
            best = {i: max(per_step[s]["contribution"][i] for s in case.targets) for i in imps}
            good, why = check_order(rk, best, [best[i] for i in rank_by(best)], REL_G3, sc)
            ck.ok(good, f"{case.name}/{eid}/summary/ranking", rank_by(best), why or [name_of(x) for x in rk])
        if L is not None:
            for kind, kname in KIND_NAMES.items():
                for i in imps:
                    cand = [(per_step[s]["limits"][kind][i][1], s) for s in case.targets
                            if per_step[s]["limits"][kind][i][0] == "limit"]
                    if not cand:
                        continue
                    val, stp = min(cand)
                    got = ck.guard(f"{case.name}/{eid}/summary/{i}/{kind}", lambda: rd(
                        cmd, "summary_tightest_value", endpoint=eid, kind=kname, imp=i))
                    if got is not None:
                        ck.num(f"{case.name}/{eid}/summary/{i}/{kind}", val, got, REL_G3)
                        gs = ck.guard(f"{case.name}/{eid}/summary/{i}/{kind}/step", lambda: rd(
                            cmd, "summary_tightest_step", endpoint=eid, kind=kname, imp=i))
                        if gs is not None:
                            ck.ok(int(gs) == stp or close(val, min(c[0] for c in cand if c[1] == int(gs)), REL_G3),
                                  f"{case.name}/{eid}/summary/{i}/{kind}/step", stp, gs)


def gate_g3(states):
    out, ok = {}, True
    for st in states:
        if st.case.waste_only:
            continue
        ck = Checks()
        try:
            cmd = st.run_command()
            ck.ok(st.rc == 0, f"{st.case.name}/exit", 0, st.rc)
            compare_linear(st, cmd, ck)
        except GateError as error:
            ck.ok(False, f"{st.case.name}/run", "command ran", str(error))
        out[st.case.name] = ck.summary(command=st.cmd_info, solves=len(st.pure))
        ok = ok and out[st.case.name]["pass"]
    return {"pass": ok, "cases": out}


