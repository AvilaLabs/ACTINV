def level_set(case, base_levels, overrides):
    lv = dict(base_levels)
    lv.update(overrides)
    return lv


class Solves:
    """Full-material solves of a case by impurity levels."""

    def __init__(self, st):
        self.st = st
        self.n = 0

    def at(self, levels, tag):
        comp = composition(self.st.case, levels)
        if comp is None:
            return None
        compact, path = self.st.solver.solve(full_spec(self.st.case, comp, f"P157 checker {self.st.case.name} {tag}"))
        return compact, path, comp


def impact_order(st):
    """Impurities by worst-case impact over the linear endpoints and targets, largest first."""
    case, score = st.case, {i: 0.0 for i in st.case.imps}
    for ep in case.endpoints:
        if ep["response"] in LINEAR or ep["response"].startswith("activity:"):
            for step in case.targets:
                a = analyse(st.r(ep, step), case.balance, case.matrix, case.imps)
                for i, (nom, lo, hi) in case.imps.items():
                    score[i] = max(score[i], abs(a["gradient"][i]) * (hi - lo) / (abs(a["nominal"]) or 1.0))
    return sorted(score, key=lambda i: (-score[i], i))


def enumerate_corners(st, sv, enum, held_levels):
    """[(label, compact, path, composition)] for all corners of `enum`, `held_levels` fixed for the others."""
    case, rows = st.case, []
    for lab, lv in corners(enum, case.imps):
        got = sv.at({**held_levels, **lv}, "corner " + ",".join(f"{i}={lab[i]}" for i in enum) + " held " + canonical(held_levels))
        if got is not None:
            rows.append((lab, got[0], got[1], got[2]))
    return rows


def held_for(st, cmd, ep, step, held):
    """Held impurities' worst-case levels for (endpoint, step): own gradient sign (linear) or the reported one."""
    case = st.case
    if ep["response"] in LINEAR or ep["response"].startswith("activity:"):
        a = analyse(st.r(ep, step), case.balance, case.matrix, case.imps)
        return {i: a["worst_level"][i] for i in held}
    out = {}
    for i in held:
        g = rd(cmd, "gradient", endpoint=endpoint_id(ep), step=step, imp=i)
        out[i] = case.imps[i][2] if g > 0.0 else case.imps[i][1]
    return out


def gate_g4_case(st, clr):
    case, ck = st.case, Checks()
    cmd = st.run_command()
    sv = Solves(st)
    scalars = [e for e in case.endpoints if e["response"] != "waste_class"]
    nominal = case.nominal()
    # (b) worst-case corners by full solve; (a) limits by full solve
    for ep in scalars:
        eid, L = endpoint_id(ep), ep.get("limit")
        for step in case.targets:
            kw = {"endpoint": eid, "step": step}
            tag = f"{case.name}/{eid}/step{step}"
            reported = ck.guard(f"{tag}/worst_value", lambda: rd(cmd, "worst_value", **kw))
            corner = ck.guard(f"{tag}/worst_corner", lambda: rd(cmd, "worst_corner", **kw))
            if reported is None or corner is None:
                continue
            try:
                lab = parse_corner(corner, case.imps)
            except SchemaError as error:
                ck.ok(False, f"{tag}/worst_corner", "complete", str(error))
                continue
            if any(m is None for i, m in lab.items() if isinstance(corner[i], str)):
                ck.ok(False, f"{tag}/worst_corner", "min or max", corner)
                continue
            lv = {i: (corner[i] if not isinstance(corner[i], str) else corner_levels({i: lab[i]}, case.imps)[i])
                  for i in case.imps}
            got = sv.at(lv, f"worst {eid} step{step}")
            if got is None:
                ck.ok(False, f"{tag}/worst_corner_solve", "feasible composition", lv)
                continue
            ck.num(f"{tag}/worst_corner_solve", reported, endpoint_value(got[0], step, ep, clr), REL_G4)
            if L is None:
                continue
            for kind, kname in KIND_NAMES.items():
                for i in case.imps:
                    status = ck.guard(f"{tag}/{i}/{kind}/status", lambda: rd(cmd, "limit_status", imp=i, kind=kname, **kw))
                    if status is None or norm_status(status) != "limit":
                        continue
                    wstar = ck.guard(f"{tag}/{i}/{kind}/value", lambda: rd(cmd, "limit_value", imp=i, kind=kname, **kw))
                    if wstar is None:
                        continue
                    if kind == "alone":
                        lev = {i: wstar}
                    elif kind == "others_nominal":
                        lev = {**nominal, i: wstar}
                    else:
                        lev = {**lv, i: wstar}
                    sol = sv.at(lev, f"limit {eid} step{step} {i} {kind}")
                    if sol is None:
                        ck.notes.append(f"{tag}/{i}/{kind}: limit {wstar} wt% leaves no balance; not solved")
                        continue
                    ck.num(f"{tag}/{i}/{kind}/solve", L, endpoint_value(sol[0], step, ep, clr), REL_G4)
            jst = ck.guard(f"{tag}/joint/status", lambda: rd(cmd, "joint_k_status", **kw))
            if jst is not None and norm_status(jst) == "limit":
                k = ck.guard(f"{tag}/joint/value", lambda: rd(cmd, "joint_k", **kw))
                if k is not None:
                    sol = sv.at({i: k * v for i, v in nominal.items()}, f"joint {eid} step{step}")
                    if sol is None:
                        ck.notes.append(f"{tag}/joint: k {k} leaves no balance; not solved")
                    else:
                        ck.num(f"{tag}/joint/solve", L, endpoint_value(sol[0], step, ep, clr), REL_G4)
    # (c) all 2^n corners
    order = impact_order(st)
    enum = order[:6]
    held = [i for i in case.imps if i not in enum]
    enum = [i for i in case.imps if i in enum]
    ck.notes.append(f"{case.name}: corners enumerated over {enum}; held at worst setting: {held}"
                    if held else f"{case.name}: all {len(enum)} impurities enumerated (2^{len(enum)} corners)")
    corner_sets = {}
    for ep in scalars:
        for step in case.targets:
            try:
                h = held_for(st, cmd, ep, step, held)
            except SchemaError as error:
                ck.ok(False, f"{case.name}/{endpoint_id(ep)}/step{step}/held", "gradient reported", str(error))
                continue
            key = canonical(h)
            if key not in corner_sets:
                corner_sets[key] = (h, enumerate_corners(st, sv, enum, h))
            rows = corner_sets[key][1]
            eid = endpoint_id(ep)
            reported = ck.guard(f"{case.name}/{eid}/step{step}/worst_value", lambda: rd(cmd, "worst_value", endpoint=eid, step=step))
            if reported is None:
                continue
            vals = [endpoint_value(c, step, ep, clr) for _, c, _, _ in rows]
            top = max(vals)
            ck.ok(top <= reported * (1 + REL_G4) + ABS_FLOOR * abs(reported) or top <= reported + 1e-30,
                  f"{case.name}/{eid}/step{step}/no corner above worst", reported, top)
            ck.num(f"{case.name}/{eid}/step{step}/worst attained", top, reported, REL_G4) if not held else \
                ck.ok(reported >= top * (1 - REL_G4), f"{case.name}/{eid}/step{step}/worst attained", top, reported)
    # (d) verification block
    ok_flag = ck.guard(f"{case.name}/verification", lambda: rd(cmd, "verification_ok"))
    if ok_flag is not None:
        ck.ok(ok_flag is True, f"{case.name}/verification reports success", True, ok_flag)
    dev = ck.guard(f"{case.name}/verification dev", lambda: rd(cmd, "verification_dev"))
    if dev is not None:
        ck.ok(dev <= REL_G4, f"{case.name}/verification max_rel_dev", f"<= {REL_G4}", dev)
    pts = ck.guard(f"{case.name}/verification points", lambda: rd(cmd, "verification_points"))
    n_points = 0
    for pt in (pts if isinstance(pts, list) else list((pts or {}).values())):
        comp = ck.guard(f"{case.name}/verification point composition", lambda: walk(pt, OUT["point_composition"]))
        if comp is None:
            continue
        compact, _ = st.solver.solve(full_spec(case, {el_key(k): v for k, v in comp.items() if v > 0.0},
                                               f"P157 checker {case.name} verification point"))
        n_points += 1
        for ep in scalars:
            for step in case.targets:
                v = walk(pt, OUT["point_solved"].format(endpoint=endpoint_id(ep), step=step), True)
                if v is MISSING:
                    ck.ok(False, f"{case.name}/verification point/{endpoint_id(ep)}/{step}", "present",
                          "schema key not found: " + OUT["point_solved"])
                    continue
                ck.num(f"{case.name}/verification point/{endpoint_id(ep)}/{step}",
                       endpoint_value(compact, step, ep, clr), v, REL_G4)
    # (e) dose.contact_proxy by removing each impurity
    for ep in [e for e in scalars if e["response"] == "dose.contact_proxy"]:
        for step in case.targets:
            kw = {"endpoint": endpoint_id(ep), "step": step}
            base = sv.at(nominal, "nominal")
            mine = {}
            for i in case.imps:
                without = sv.at({**nominal, i: 0.0}, f"without {i}")
                mine[i] = endpoint_value(base[0], step, ep, clr) - endpoint_value(without[0], step, ep, clr)
                got = ck.guard(f"{case.name}/dose/step{step}/{i}/contribution", lambda: rd(cmd, "contribution_nominal", imp=i, **kw))
                if got is not None:
                    ck.num(f"{case.name}/dose/step{step}/{i}/contribution", mine[i], got, REL_G4,
                           endpoint_value(base[0], step, ep, clr))
            rank = ck.guard(f"{case.name}/dose/step{step}/ranking", lambda: rd(cmd, "ranking", **kw))
            if rank is not None:
                good, why = check_order(rank, mine, [mine[i] for i in rank_by(mine)], REL_G4,
                                        endpoint_value(base[0], step, ep, clr))
                ck.ok(good, f"{case.name}/dose/step{step}/ranking", rank_by(mine), why or [name_of(x) for x in rank])
    return ck.summary(command=st.cmd_info, full_solves=len(sv.st.solver.index), verification_points=n_points,
                      enumerated=enum, held=held)


def gate_g4(states, clr):
    out, ok = {}, True
    for st in states:
        if st.case.waste_only:
            continue
        try:
            out[st.case.name] = gate_g4_case(st, clr)
        except (GateError, SchemaError) as error:
            out[st.case.name] = {"pass": False, "error": str(error)}
        ok = ok and out[st.case.name]["pass"]
    return {"pass": ok, "cases": out}


