#!/usr/bin/env python3
"""P148 R5: changed baselines, old binary against candidate.

Usage: p148_r5.py OLD_BIN NEW_BIN OUT_DIR [--spec NAME=SPEC.json ...]

For each committed result that a CI control regenerates and that P148 changes:
  - P15 cache integrity (`results/p15_cache_integrity.json`): the control's fixture spec is run with both binaries;
    the old binary must reproduce the committed pre-P148 normalized-result hash (taken from git at the opening
    commit), the new binary the committed hash in the working tree, and every difference between the two results is
    classified by `p148_baselines`.
  - P110 composition solve (`results/g1_p110_composition_solve.json`): `check_p110.py --no-write` is run with each
    binary; the old run must match the committed pre-P148 record, the new run the regenerated record, and the nine
    case outputs are classified.
  - Each `--spec` (the CI end-to-end spec, `ci_end_to_end`, and the P10 legacy neutron spec, `p10_legacy`, as
    written by their controls) is run with both binaries and the results are classified. For `p10_legacy` the old
    result must also reproduce the pre-P148 `PRE_P10_NEUTRON_NORMALIZED_SHA256` and the new one the re-seated value.
Each regenerated committed record is also compared with its opening version.
The record goes to OUT_DIR/r5.json. R5 passes when every difference is pruning, hash or bounded.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import g3_p15_cache_integrity as p15  # noqa: E402
import p148_baselines  # noqa: E402

OPENING = "364a73e04761a322eb27ab86289c8c6fd9a0032c"
# Committed records regenerated by the candidate; each may differ from its opening version only in hashes.
RECORDS = ("results/p15_cache_integrity.json", "results/g1_p110_composition_solve.json",
           "results/g2_p110_composition_solve.json")


def committed(path: str, revision: str = OPENING) -> dict:
    return json.loads(subprocess.run(["git", "show", f"{revision}:{path}"], cwd=ROOT, check=True,
                                     capture_output=True, text=True).stdout)


def p15_case(old_bin: Path, new_bin: Path, out: Path) -> dict:
    old_hash = committed("results/p15_cache_integrity.json")["deletion_recreation"]["normalized_result_sha256"]
    new_hash = json.loads((ROOT / "results/p15_cache_integrity.json").read_text())[
        "deletion_recreation"]["normalized_result_sha256"]
    with tempfile.TemporaryDirectory(prefix="p148-r5-p15-", dir=os.environ.get("TMPDIR")) as directory:
        work = Path(directory)
        spec = p15.fixture(work)
        hashes = {}
        for label, binary in (("old", old_bin), ("new", new_bin)):
            p15.ACTINV = binary
            output = work / f"{label}.json"
            completed = p15.run(spec, work / f"cache-{label}", output)
            if completed.returncode:
                raise SystemExit(f"P15 {label} run failed: {completed.stderr}")
            hashes[label] = p15.canonical_sha256(p15.normalized(output), work)
            (out / "p15").mkdir(parents=True, exist_ok=True)
            (out / "p15" / f"{label}.json").write_text(
                json.dumps(p15.normalized(output), sort_keys=True, indent=1) + "\n")
    diff = p148_baselines.compare(out / "p15" / "old.json", out / "p15" / "new.json")
    return {"baseline": "results/p15_cache_integrity.json",
            "old_reproduces_committed": hashes["old"] == old_hash,
            "new_matches_regenerated": hashes["new"] == new_hash,
            "hashes": hashes, "committed": {"old": old_hash, "new": new_hash}, "diff": diff,
            "pass": hashes["old"] == old_hash and hashes["new"] == new_hash and diff["pass"]}


def p110_case(old_bin: Path, new_bin: Path, out: Path) -> dict:
    record = "results/g1_p110_composition_solve.json"
    outputs = ROOT / "target/p110-controls/outputs"
    matches = {}
    old_record = committed(record)
    for label, binary in (("old", old_bin), ("new", new_bin)):
        target = ROOT / record
        saved = target.read_text()
        if label == "old":
            # The old binary is judged against the pre-P148 record, restored for this run only.
            target.write_text(json.dumps(old_record, sort_keys=True, indent=2) + "\n")
        try:
            completed = subprocess.run([sys.executable, "controls/check_p110.py", "--no-write"], cwd=ROOT,
                                       env={**os.environ, "ACTINV_BIN": str(binary)}, capture_output=True, text=True)
        finally:
            target.write_text(saved)
        reports = []
        decoder, text, index = json.JSONDecoder(), completed.stdout, 0
        while text[index:].strip():
            stripped = text[index:].lstrip()
            value, end = decoder.raw_decode(stripped)
            reports.append(value)
            index = len(text) - len(stripped) + end
        g1 = next(r for r in reports if r.get("schema") == "actinv-p110-composition-solve-g1-1")
        matches[label] = g1.get("persisted_result_matches") is True
        destination = out / "p110" / label
        shutil.rmtree(destination, ignore_errors=True)
        shutil.copytree(outputs, destination, ignore=shutil.ignore_patterns("*.repeat.json"))
    diff = p148_baselines.compare(out / "p110" / "old", out / "p110" / "new")
    return {"baseline": record, "old_reproduces_committed": matches["old"], "new_matches_regenerated": matches["new"],
            "diff": diff, "pass": matches["old"] and matches["new"] and diff["pass"]}


def spec_case(name: str, spec: Path, old_bin: Path, new_bin: Path, out: Path) -> dict:
    results = {}
    (out / name).mkdir(parents=True, exist_ok=True)
    for label, binary in (("old", old_bin), ("new", new_bin)):
        path = out / name / f"{label}.json"
        subprocess.run([str(binary), "run", str(spec), str(path)], cwd=ROOT, check=True, capture_output=True)
        results[label] = json.loads(path.read_text())
        # Timing is not a result.
        results[label].pop("ms", None)
        path.write_text(json.dumps(results[label], sort_keys=True, indent=1) + "\n")
    case = {"baseline": name, "spec": str(spec), "diff": p148_baselines.compare(out / name / "old.json",
                                                                             out / name / "new.json")}
    case["pass"] = case["diff"]["pass"]
    if name == "p10_legacy":
        import g6_p10_projectile_runtime as p10
        source = subprocess.run(["git", "show", f"{OPENING}:controls/g6_p10_projectile_runtime.py"], cwd=ROOT,
                                check=True, capture_output=True, text=True).stdout
        old_expected = re.search(r'PRE_P10_NEUTRON_NORMALIZED_SHA256 = \(\s*"([0-9a-f]{64})"', source).group(1)
        hashes = {label: p10.canonical_result_hash(value) for label, value in results.items()}
        case.update({"hashes": hashes, "expected": {"old": old_expected,
                                                    "new": p10.PRE_P10_NEUTRON_NORMALIZED_SHA256},
                     "old_reproduces_committed": hashes["old"] == old_expected,
                     "new_matches_regenerated": hashes["new"] == p10.PRE_P10_NEUTRON_NORMALIZED_SHA256})
        case["pass"] = case["pass"] and case["old_reproduces_committed"] and case["new_matches_regenerated"]
    return case


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("old_bin", type=Path)
    ap.add_argument("new_bin", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--spec", action="append", default=[])
    args = ap.parse_args()
    old_bin, new_bin, out = args.old_bin.resolve(), args.new_bin.resolve(), args.out
    out.mkdir(parents=True, exist_ok=True)
    cases = [p15_case(old_bin, new_bin, out), p110_case(old_bin, new_bin, out)]
    for item in args.spec:
        name, spec = item.split("=", 1)
        cases.append(spec_case(name, Path(spec).resolve(), old_bin, new_bin, out))
    records = {}
    for path in RECORDS:
        (out / "records").mkdir(exist_ok=True)
        old = out / "records" / (Path(path).stem + ".old.json")
        old.write_text(json.dumps(committed(path)) + "\n")
        records[path] = p148_baselines.compare(old, ROOT / path)
    record = {"schema": "actinv-p148-r5-1", "opening_commit": OPENING, "cases": cases, "records": records,
              "pass": all(c["pass"] for c in cases) and all(r["other"] == 0 for r in records.values())}
    (out / "r5.json").write_text(json.dumps(record, indent=1) + "\n")
    print(json.dumps([{k: c.get(k) for k in ("baseline", "old_reproduces_committed", "new_matches_regenerated", "pass")}
                      | {"counts": {d: v["counts"] for d, v in c["diff"]["documents"].items()}} for c in cases],
                     indent=1))
    return 0 if record["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
