    fn dirty(&self) -> bool {
        self.raw_dirty || self.document != self.saved || self.base != self.saved_base
    }
    fn report(&mut self, result: Result<String, String>) {
        match result {
            Ok(s) => {
                self.status = s;
                self.error = false;
            }
            Err(e) => {
                self.status = e;
                self.error = true;
            }
        }
    }
    fn request(&mut self, p: Pending) {
        if self.dirty() {
            self.pending = Some(p);
        } else {
            self.perform(p);
        }
    }
    fn perform(&mut self, p: Pending) {
        match p {
            Pending::Open => {
                if let Some(path) = self
                    .platform
                    .pick_file(Dialog::new().filter("ACTINV problem", &["json"]))
                {
                    let result = std::fs::read_to_string(&path)
                        .map_err(|e| e.to_string())
                        .and_then(|s| model::decode_problem(&s));
                    match result {
                        Ok(doc) => {
                            self.document = doc;
                            self.saved = self.document.clone();
                            self.saved_base = self.base.clone();
                            self.base = path.parent().unwrap_or(std::path::Path::new(".")).into();
                            self.saved_base = self.base.clone();
                            self.path = Some(path);
                            self.raw_dirty = false;
                            self.undo.clear();
                            self.redo.clear();
                            self.page = Page::Overview;
                            self.report(Ok("Problem opened. Relative input paths use the problem's folder; change Input base if needed.".into()));
                        }
                        Err(e) => self.report(Err(e)),
                    }
                }
            }
            Pending::Example => {
                self.document = model::decode_problem(model::EXAMPLE).unwrap();
                self.saved = self.document.clone();
                self.saved_base = self.base.clone();
                self.path = None;
                self.base = model::working_directory();
                self.saved_base = self.base.clone();
                self.raw_dirty = false;
                self.undo.clear();
                self.redo.clear();
                self.page = Page::Overview;
            }
            Pending::Close => {}
        }
    }
    fn save_problem(&mut self) -> bool {
        if self.raw_dirty {
            self.report(Err("Apply or discard your JSON edits before saving.".into()));
            return false;
        }
        let path = self.path.clone().or_else(|| {
            self.platform.save_file(
                Dialog::new()
                    .filter("JSON", &["json"])
                    .file_name("problem.json"),
            )
        });
        if let Some(path) = path {
            // Save resolved paths so Save As cannot silently change input meaning.
            let value = if path.parent() != Some(self.base.as_path()) {
                match model::resolve_inputs(&self.document, &self.base)
                    .and_then(|s| serde_json::to_value(s).map_err(|e| e.to_string()))
                {
                    Ok(v) => v,
                    Err(e) => {
                        self.report(Err(e));
                        return false;
                    }
                }
            } else {
                self.document.clone()
            };
            match model::write_json(&path, &value) {
                Ok(()) => {
                    self.document = value;
                    self.saved = self.document.clone();
                    self.saved_base = self.base.clone();
                    self.path = Some(path);
                    self.report(Ok("Problem saved.".into()));
                    return true;
                }
                Err(e) => self.report(Err(e)),
            }
        }
        false
    }
    fn validate(&self) -> Result<Spec, String> {
        if self.raw_dirty {
            return Err("Apply or discard your JSON edits before validating or running.".into());
        }
        let spec = model::resolve_inputs(&self.document, &self.base)?;
        model::check_files(&spec)?;
        Ok(spec)
    }
    fn run(&mut self, _ctx: &egui::Context) {
        if self.result_unsaved {
            self.result_guard = Some(ResultAction::Run);
            return;
        }
        match self.validate() {
            Err(e) => self.report(Err(e)),
            Ok(spec) => {
                let cache = std::env::temp_dir().join(format!(
                    "actinv-gui-calc-{}-{}",
                    std::process::id(),
                    std::time::SystemTime::now()
                        .duration_since(std::time::UNIX_EPOCH)
                        .unwrap_or_default()
                        .as_nanos()
                ));
                let handle = match crate::worker::spawn(spec, cache.clone()) {
                    Ok(h) => h,
                    Err(error) => {
                        self.report(Err(error));
                        return;
                    }
                };
                self.job = Some(Job {
                    rx: None,
                    handle: Some(handle),
                    started: Instant::now(),
                    kind: JobKind::Calculation,
                    cancelled: false,
                });
                self.report(Ok(
                    "Preparing isolated calculation workspace, then solving… Every run prepares a private cache and may take longer.".into(),
                ));
            }
        }
    }
    fn open_result(&mut self, ctx: &egui::Context, compare: bool) {
        if !compare && self.result_unsaved {
            self.result_guard = Some(ResultAction::Open);
            return;
        }
        if let Some(path) = self
            .platform
            .pick_file(Dialog::new().filter("ACTINV result", &["json"]))
        {
            // Results can be hundreds of MB: read, parse and validate them off the UI
            // thread so the window keeps repainting; `logic` installs the outcome.
            let (tx, rx) = mpsc::channel();
            let ctx = ctx.clone();
            std::thread::spawn(move || {
                let loaded = std::fs::read_to_string(&path)
                    .map_err(|e| e.to_string())
                    .and_then(|s| serde_json::from_str(&s).map_err(|e| e.to_string()))
                    .and_then(|v| {
                        ResultDocument::parse(
                            v,
                            path.file_name()
                                .unwrap_or_default()
                                .to_string_lossy()
                                .into(),
                        )
                    });
                let _ = tx.send(loaded);
                ctx.request_repaint();
            });
            self.result_load = Some((compare, rx));
            self.report(Ok("Loading result…".into()));
        }
    }
    fn install_result(&mut self, loaded: Result<ResultDocument, String>, compare: bool) {
        match loaded {
            Ok(r) => {
                if compare {
                    self.comparison = Some(r);
                } else {
                    self.result = Some(r);
                    self.result_unsaved = false;
                    self.step = 0;
                    self.selected.clear();
                }
                self.reset_plot = true;
                self.page = Page::Results;
                self.report(Ok("Result loaded.".into()));
            }
            Err(e) => self.report(Err(e)),
        }
    }
    fn export(&mut self, csv: bool) {
        let Some(result) = &self.result else {
            return;
        };
        if let Some(path) = self.platform.save_file(Dialog::new().file_name(if csv {
            "inventory.csv"
        } else {
            "result.json"
        })) {
            let r = if csv {
                model::inventory_csv(result, self.step)
                    .and_then(|csv| std::fs::write(path, csv).map_err(|e| e.to_string()))
            } else {
                model::write_json(&path, &result.value)
            };
            if r.is_ok() && !csv {
                self.result_unsaved = false;
            }
            self.report(r.map(|()| "Export saved.".into()));
        }
    }
