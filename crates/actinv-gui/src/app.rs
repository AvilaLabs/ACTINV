impl eframe::App for Desktop {
    fn persist_egui_memory(&self) -> bool {
        self.capture.is_none()
    }
    fn save(&mut self, storage: &mut dyn eframe::Storage) {
        if self.capture.is_none() {
            eframe::set_value(storage, "actinv-theme", &self.theme);
        }
    }
    fn logic(&mut self, ctx: &egui::Context, _: &mut eframe::Frame) {
        // eframe restores its own context memory after app construction.
        // Our explicit appearance preference remains authoritative after restoration.
        self.apply_theme(ctx);
        let polled = self
            .result_load
            .as_ref()
            .map(|(compare, rx)| (*compare, rx.try_recv()));
        match polled {
            Some((compare, Ok(loaded))) => {
                self.result_load = None;
                self.install_result(loaded, compare);
            }
            Some((_, Err(mpsc::TryRecvError::Disconnected))) => {
                self.result_load = None;
                self.report(Err("result loading stopped unexpectedly".into()));
            }
            Some((_, Err(mpsc::TryRecvError::Empty))) | None => {}
        }
        let result = self.job.as_ref().and_then(|job| {
            let received = if let Some(handle) = &job.handle {
                handle.rx.try_recv().map(|v| v.map(JobOutput::Calculation))
            } else {
                job.rx
                    .as_ref()
                    .expect("non-calculation job receiver")
                    .try_recv()
            };
            match received {
                Ok(v) => Some(v),
                Err(mpsc::TryRecvError::Disconnected) => Some(Err(
                    "The calculation worker stopped unexpectedly. Check the terminal output."
                        .into(),
                )),
                Err(mpsc::TryRecvError::Empty) => None,
            }
        });
        // Drain admitted sweep points — only the current generation's
        // points may render; a superseded sweep's late results are dropped.
        let mut sweep_done = false;
        if let Some(handle) = &self.sweep.handle {
            loop {
                match handle.rx.try_recv() {
                    Ok(p) => {
                        if crate::sweep::admissible(self.sweep.generation, &p) {
                            self.sweep.points.push(p);
                        }
                    }
                    Err(mpsc::TryRecvError::Empty) => break,
                    Err(mpsc::TryRecvError::Disconnected) => {
                        sweep_done = true;
                        break;
                    }
                }
            }
        }
        if sweep_done {
            self.sweep.handle = None;
            self.sweep.running = false;
            self.report(Ok("Parameter sweep finished.".into()));
        }
        // Live probe (P69): a persistent worker; each landed point is a
        // certified screened solve admitted under the live generation.
        if let Some(handle) = &self.sweep.live_handle {
            while let Ok(p) = handle.rx.try_recv() {
                if crate::sweep::admissible(self.sweep.generation, &p) {
                    self.sweep.points.push(p);
                }
            }
        }
        if let Some(result) = result {
            let cancelled = self.job.as_ref().is_some_and(|job| job.cancelled);
            self.job = None;
            if cancelled {
                self.report(Ok(
                    "Calculation cancelled; the previous result and current problem were kept."
                        .into(),
                ));
            } else {
                match result {
                    Ok(JobOutput::Spectrum(preview)) => {
                        self.imported = Some(preview);
                        self.page = Page::Spectrum;
                        self.report(Ok(
                            "Transport spectrum ready. Review the preview and apply explicitly."
                                .into(),
                        ));
                    }
                    Ok(JobOutput::Data(fragment)) => {
                        self.downloaded = Some(fragment);
                        self.page = Page::Overview;
                        self.report(Ok(
                        "Data downloaded and verified. Use the installed paths below when ready."
                            .into(),
                    ));
                    }
                    Ok(JobOutput::Calculation(v)) => {
                        match ResultDocument::parse(v, "Completed calculation".into()) {
                            Ok(r) => {
                                self.result = Some(r);
                                self.result_unsaved = true;
                                self.step = 0;
                                self.selected.clear();
                                self.reset_plot = true;
                                self.page = Page::Results;
                                self.report(Ok(
                                "Calculation complete. Explore the results and review the ledger."
                                    .into(),
                            ));
                            }
                            Err(e) => self.report(Err(e)),
                        }
                    }
                    Err(e) => self.report(Err(e)),
                }
            }
        }
        if self.job.is_some() {
            ctx.request_repaint_after(Duration::from_millis(200));
        }
    }
    fn ui(&mut self, ui: &mut egui::Ui, _: &mut eframe::Frame) {
        self.render(ui);
    }
}
impl Desktop {
    fn render(&mut self, ui: &mut egui::Ui) {
        let ctx = ui.ctx().clone();
        if ctx.input(|i| i.viewport().close_requested())
            && !self.allow_close
            && (self.dirty() || self.job.is_some() || self.result_unsaved)
        {
            ctx.send_viewport_cmd(egui::ViewportCommand::CancelClose);
            if self.result_unsaved {
                self.result_guard = Some(ResultAction::Close);
            } else {
                self.pending = Some(Pending::Close);
            }
        }
        if ctx.input_mut(|i| i.consume_key(egui::Modifiers::COMMAND, egui::Key::S)) {
            self.save_problem();
        }
        if ctx.input_mut(|i| i.consume_key(egui::Modifiers::COMMAND, egui::Key::O)) {
            self.request(Pending::Open);
        }
        if ctx.input(|i| i.key_pressed(egui::Key::F1)) {
            self.help = true;
        }
        if let Some(capture) = &mut self.capture {
            capture.prepare(&ctx, &mut self.page, &mut self.tour, &mut self.result);
        }
        self.tour.anchors.clear();
        if let Some(step) = self.tour.step() {
            self.page = step.page;
        }
        self.toolbar(ui);
        egui::Panel::bottom("status")
            .resizable(true)
            .default_size(76.)
            .show(ui, |ui| {
                egui::ScrollArea::vertical().show(ui, |ui| {
                    ui.horizontal_wrapped(|ui| {
                        if let Some(job) = &self.job {
                            ui.spinner();
                            let stage = match job.kind {
                                JobKind::Calculation => "Preparing / solving",
                                JobKind::Data => "Downloading / verifying",
                                JobKind::Transport => "Reading / checking transport",
                            };
                            ui.label(format!(
                                "{stage} · {:.0}s",
                                job.started.elapsed().as_secs_f64()
                            ));
                            if job.kind == JobKind::Calculation
                                && ui.button("Cancel calculation").clicked()
                            {
                                if let Some(handle) = &job.handle {
                                    handle.request_cancel();
                                }
                                if let Some(job) = &mut self.job {
                                    job.cancelled = true;
                                }
                                self.status =
                                    "Cancellation requested; stopping the isolated worker…".into();
                                self.error = false;
                            }
                        }
                        ui.colored_label(
                            if self.error {
                                if ui.visuals().dark_mode {
                                    Color32::from_rgb(255, 145, 135)
                                } else {
                                    Color32::from_rgb(160, 40, 35)
                                }
                            } else {
                                ui.visuals().text_color()
                            },
                            &self.status,
                        );
                    });
                });
            });
        self.navigation(ui);
        let before = self.document.clone();
        egui::CentralPanel::default().show(ui,|ui|{
            egui::ScrollArea::vertical().id_salt(("page",self.page)).show(ui,|ui|{
                ui.add_space(12.);
                if self.raw_dirty && self.page.group()==Group::Setup{ui.colored_label(BLUE,"Apply or discard your pending edits in Advanced JSON to resume editing here.");}
                ui.add_enabled_ui(!self.raw_dirty||self.page.group()!=Group::Setup,|ui|{self.page_body(ui);});
            });
        });
        if before != self.document {
            self.undo.push(before);
            if self.undo.len() > 100 {
                self.undo.remove(0);
            }
            self.redo.clear();
        }
        if self.help {
            egui::Window::new("Help & walkthroughs").collapsible(false).resizable(false).default_width(430.).show(&ctx,|ui|{
            ui.heading("Let’s walk through ACTINV");ui.label("Guides highlight real controls while dimming the surrounding workspace. You can use the highlighted control, or press Next to keep exploring. Escape exits a tour.");
            ui.horizontal(|ui| { ui.label("Interface size"); let mut zoom=ctx.zoom_factor(); if ui.add(egui::Slider::new(&mut zoom,0.8..=2.).text("Scale")).changed() { ctx.set_zoom_factor(zoom); } });
            if ui.button("Start: create and run a calculation").clicked(){self.help=false;self.tour.start(false);}
            if ui.button("Start: understand and export results").clicked(){self.help=false;self.tour.start(true);}
            ui.separator();ui.label("Shortcuts: Ctrl/Cmd+O opens a problem; Ctrl/Cmd+S saves; F1 opens Help.");ui.hyperlink_to("ACTINV specification guide","https://github.com/AvilaLabs/ACTINV/blob/master/docs/SPEC.md");ui.hyperlink_to("Data setup","https://github.com/AvilaLabs/ACTINV/blob/master/docs/DATA.md");ui.hyperlink_to("Qualification and limitations","https://github.com/AvilaLabs/ACTINV/blob/master/docs/QUALIFICATION.md");if ui.button("Close help").clicked(){self.help=false;}
        });
        }
        if let Some(pending) = self.pending {
            egui::Modal::new(egui::Id::new("unsaved")).show(&ctx,|ui|{ui.heading("Keep your work?");ui.label(if self.job.is_some(){"Background work is still running. Closing the application will interrupt it."}else{"Your problem has unsaved changes. Save them before continuing, or explicitly discard them."});ui.horizontal(|ui|{
            if ui.button("Cancel").clicked(){self.pending=None;}
            if ui.button("Discard and continue").clicked(){self.pending=None;if matches!(pending,Pending::Close){self.stop_calculation_for_close();self.allow_close=true;ctx.send_viewport_cmd(egui::ViewportCommand::Close);}else{self.perform(pending);}}
            if ui.button("Save and continue").clicked()&&self.save_problem(){self.pending=None;if matches!(pending,Pending::Close){self.stop_calculation_for_close();self.allow_close=true;ctx.send_viewport_cmd(egui::ViewportCommand::Close);}else{self.perform(pending);}}
        });});
        }
        self.tour.show(&ctx);
        if let Some(action) = self.result_guard {
            egui::Modal::new(egui::Id::new("unsaved-result")).show(&ctx, |ui| {
                ui.heading("Keep your calculation result?");
                ui.label("Export the complete result as JSON before replacing it or closing ACTINV. Saving the problem or an inventory CSV does not save the full result.");
                ui.horizontal(|ui| {
                    if ui.button("Cancel").clicked() { self.result_guard = None; }
                    if ui.button("Export result JSON").clicked() { self.export(false); }
                    if ui.button(if self.result_unsaved { "Discard result and continue" } else { "Continue" }).clicked() {
                        self.result_unsaved = false;
                        self.result_guard = None;
                        match action {
                            ResultAction::Run => self.run(&ctx),
                            ResultAction::Open => self.open_result(&ctx, false),
                            ResultAction::Tutorial => { self.result = Some(model::tutorial_result()); self.step=0; self.selected.clear(); self.comparison=None; self.page=Page::Results; self.reset_plot=true; self.tour.start(true); },
                            ResultAction::Close => { if self.dirty() || self.job.is_some() { self.pending = Some(Pending::Close); } else { self.allow_close=true; ctx.send_viewport_cmd(egui::ViewportCommand::Close); } },
                        }
                    }
                });
            });
        }
        if let Some(capture) = &mut self.capture {
            capture.finish(&ctx);
        }
    }
}

fn path_field(ui: &mut egui::Ui, label: &str, value: &mut Value, platform: &dyn Platform) {
    ui.label(label);
    ui.horizontal(|ui| {
        let mut s = value.as_str().unwrap_or("").to_owned();
        if ui
            .add(
                egui::TextEdit::singleline(&mut s)
                    .desired_width((ui.available_width() - 100.).max(160.)),
            )
            .changed()
        {
            *value = s.into();
        }
        if ui.button("Browse…").clicked() {
            if let Some(p) = platform.pick_file(Dialog::new()) {
                *value = p.to_string_lossy().into_owned().into();
            }
        }
    });
}

