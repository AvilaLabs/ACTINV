impl eframe::App for Desktop {
    fn persist_egui_memory(&self) -> bool {
        self.capture.is_none()
    }
    fn save(&mut self, storage: &mut dyn eframe::Storage) {
        if self.capture.is_none() {
            eframe::set_value(storage, "actinv-theme", &self.theme);
        }
    }
    fn logic(&mut self, ctx: &egui::Context, _: &mut eframe::Frame) {
        // eframe restores its own context memory after app construction.
        // Our explicit appearance preference remains authoritative after restoration.
        self.apply_theme(ctx);
        let polled = self
            .result_load
            .as_ref()
            .map(|(compare, rx)| (*compare, rx.try_recv()));
        match polled {
            Some((compare, Ok(loaded))) => {
                self.result_load = None;
                self.install_result(loaded, compare);
            }
            Some((_, Err(mpsc::TryRecvError::Disconnected))) => {
                self.result_load = None;
                self.report(Err("result loading stopped unexpectedly".into()));
            }
            Some((_, Err(mpsc::TryRecvError::Empty))) | None => {}
        }
        let result = self.job.as_ref().and_then(|job| {
            let received = if let Some(handle) = &job.handle {
                let kind = job.kind;
                handle.rx.try_recv().map(|v| {
                    v.and_then(|value| match kind {
                        JobKind::Screen => Ok(JobOutput::Screen(value)),
                        JobKind::Command(_) => {
                            crate::jobs::JobResult::from_value(&value).map(JobOutput::Command)
                        }
                        _ => Ok(JobOutput::Calculation(value)),
                    })
                })
            } else {
                job.rx
                    .as_ref()
                    .expect("non-calculation job receiver")
                    .try_recv()
            };
            match received {
                Ok(v) => Some(v),
                Err(mpsc::TryRecvError::Disconnected) => Some(Err(
                    "The calculation worker stopped unexpectedly. Check the terminal output."
                        .into(),
                )),
                Err(mpsc::TryRecvError::Empty) => None,
            }
        });
        // Drain admitted sweep points — only the current generation's
        // points may render; a superseded sweep's late results are dropped.
        let mut sweep_done = false;
        if let Some(handle) = &self.sweep.handle {
            loop {
                match handle.rx.try_recv() {
                    Ok(p) => {
                        if crate::sweep::admissible(self.sweep.generation, &p) {
                            self.sweep.points.push(p);
                        }
                    }
                    Err(mpsc::TryRecvError::Empty) => break,
                    Err(mpsc::TryRecvError::Disconnected) => {
                        sweep_done = true;
                        break;
                    }
                }
            }
        }
        if sweep_done {
            self.sweep.handle = None;
            self.sweep.running = false;
            self.report(Ok("Parameter sweep finished.".into()));
        }
        // Live probe (P69): a persistent worker; each landed point is a
        // certified screened solve admitted under the live generation.
        if let Some(handle) = &self.sweep.live_handle {
            while let Ok(p) = handle.rx.try_recv() {
                if crate::sweep::admissible(self.sweep.generation, &p) {
                    self.sweep.points.push(p);
                }
            }
        }
        if let Some(result) = result {
            let cancelled = self.job.as_ref().is_some_and(|job| job.cancelled);
            self.job = None;
            if cancelled {
                self.report(Ok(
                    "Calculation cancelled; the previous result and current problem were kept."
                        .into(),
                ));
            } else {
                match result {
                    Ok(JobOutput::Spectrum(preview)) => {
                        self.imported = Some(preview);
                        self.page = Page::Spectrum;
                        self.report(Ok(
                            "Transport spectrum ready. Review the preview and apply explicitly."
                                .into(),
                        ));
                    }
                    Ok(JobOutput::Data(fragment)) => {
                        self.downloaded = Some(fragment);
                        self.page = Page::Data;
                        self.report(Ok(
                            "Data downloaded and verified. Use them for this problem on this page."
                                .into(),
                        ));
                    }
                    Ok(JobOutput::Command(done)) => self.command_finished(done),
                    Ok(JobOutput::Screen(v)) => {
                        self.screen_finished("Completed screen".into(), v);
                    }
                    Ok(JobOutput::Calculation(v)) => {
                        match ResultDocument::parse(v, "Completed calculation".into()) {
                            Ok(r) => {
                                self.step = crate::views::summary::shutdown_step(&r).unwrap_or(0);
                                self.result = Some(r);
                                self.result_unsaved = true;
                                self.selected.clear();
                                self.reset_plot = true;
                                self.page = Page::Summary;
                                self.report(Ok(
                                "Calculation complete. Save result… keeps it; Export saves a report, charts and tables."
                                    .into(),
                            ));
                            }
                            Err(e) => self.report(Err(e)),
                        }
                    }
                    Err(e) => self.report(Err(e)),
                }
            }
        }
        if self.job.is_some() {
            ctx.request_repaint_after(Duration::from_millis(200));
        }
    }
    fn ui(&mut self, ui: &mut egui::Ui, _: &mut eframe::Frame) {
        self.render(ui);
    }
}
