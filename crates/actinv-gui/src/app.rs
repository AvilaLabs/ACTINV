/// Editable sweep-panel state — no numerics here; every point's spec is
/// generated by `sweep::sweep_specs` and solved by the qualified worker path.
struct SweepUi {
    axis: usize,
    element: String,
    step_index: usize,
    lo: f64,
    hi: f64,
    count: usize,
    response: crate::sweep::SweepResponse,
    step_row: usize,
    handle: Option<crate::sweep::SweepHandle>,
    generation: u64,
    points: Vec<crate::sweep::CompletedPoint>,
    running: bool,
    /// D1/P68: certified-screening tier — in-process shared-cache solves
    /// with the P65 screen certificate on every point.
    screened: bool,
    /// D1/P69: live certified probe — a persistent worker on one shared
    /// cache; the slider submits only the newest position.
    live: bool,
    live_handle: Option<crate::sweep::LiveSweepHandle>,
    live_value: f64,
    /// D1/P71: live frontier view — (activity, heat) pairs of landed
    /// points rendered as a Pareto plot; the nondominated staircase
    /// recomputes as points stream in.
    frontier: bool,
}

